import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { JSDOM } from 'jsdom';
import { IDBFactory } from 'fake-indexeddb';
import { openStore, loadSnapshot } from '../dist/storage.js';
import { TaskRepository } from '../dist/database.js';
const require=createRequire(import.meta.url);
const initSQL=require('../dist/vendor/sql-wasm.js');
const waitFor=async predicate=>{for(let i=0;i<100;i++){if(predicate())return;await new Promise(r=>setTimeout(r,10));}throw new Error('UI did not reach expected state.');};

test('DOM integration: create, validate, edit, complete/reopen, delete/restore, search, category, theme and durable SQL', async()=>{
  const html=await readFile(new URL('../dist/index.html',import.meta.url),'utf8');
  const dom=new JSDOM(html,{url:'https://daymind.test/',pretendToBeVisual:true});
  const {window}=dom;const factory=new IDBFactory();const SQL=await initSQL({wasmBinary:await readFile(new URL('../dist/vendor/sql-wasm.wasm',import.meta.url))});
  Object.assign(globalThis,{window,document:window.document,location:window.location,history:window.history,localStorage:window.localStorage,FormData:window.FormData,indexedDB:factory});
  Object.defineProperty(globalThis,'navigator',{configurable:true,value:window.navigator});
  globalThis.BroadcastChannel=class{postMessage(){}addEventListener(){}};
  window.initSqlJs=async()=>SQL;
  window.HTMLDialogElement.prototype.showModal=function(){this.setAttribute('open','');};
  window.HTMLDialogElement.prototype.close=function(){this.removeAttribute('open');};
  const savedInterval=globalThis.setInterval;globalThis.setInterval=()=>0;
  await import('../dist/app.js');
  const $=selector=>window.document.querySelector(selector);
  const click=selector=>{assert.ok($(selector),selector);$(selector).click();};
  const submit=selector=>$(selector).dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));
  await waitFor(()=>$('#save-status').textContent==='Đã lưu trên thiết bị');globalThis.setInterval=savedInterval;
  assert.match($('#task-list').textContent,/Một ngày đang rộng mở/);
  $('#quick-title').value='Đi dạo không có hạn';submit('#quick-add');
  await waitFor(()=>$('#task-list').textContent.includes('Đi dạo không có hạn'));
  assert.equal($('#breadcrumb-title').textContent,'Hộp thư');assert.match($('#task-list').textContent,/Không thời hạn/);
  click('#add-task');const form=$('#task-form');
  assert.equal(form.elements.dueAt.value,'');
  form.elements.title.value='<img src=x onerror=alert(1)>';
  form.elements.categoryId.value='personal';form.elements.priority.value='HIGH';submit('#task-form');
  await waitFor(()=>!$('#task-dialog').hasAttribute('open'));
  assert.equal($('#task-list img'),null);assert.match($('#task-list').textContent,/<img src=x onerror=alert\(1\)>/);
  const target=()=>[...window.document.querySelectorAll('.task-row')].find(el=>el.textContent.includes('<img'));
  target().querySelector('.task-title').click();form.elements.title.value='Tập trung 25 phút';
  form.elements.scheduledStartAt.value='2026-11-10T10:00';form.elements.scheduledEndAt.value='2026-11-10T09:00';submit('#task-form');
  await waitFor(()=>!$('#form-error').hidden);assert.match($('#form-error').textContent,/kết thúc/);
  form.elements.scheduledEndAt.value='2026-11-10T11:00';form.elements.status.value='IN_PROGRESS';submit('#task-form');
  await waitFor(()=>!$('#task-dialog').hasAttribute('open'));
  let row=[...window.document.querySelectorAll('.task-row')].find(el=>el.textContent.includes('Tập trung'));
  assert.match(row.textContent,/Đang làm/);row.querySelector('[data-action=toggle]').click();
  await waitFor(()=>$('#stat-done-value').textContent==='1');
  click('[data-view=completed]');assert.match($('#task-list').textContent,/Tập trung/);
  $('#task-list [data-action=toggle]').click();await waitFor(()=>!$('#task-list').textContent.includes('Tập trung'));
  click('[data-view=all]');row=[...window.document.querySelectorAll('.task-row')].find(el=>el.textContent.includes('Tập trung'));
  row.querySelector('.task-title').click();click('#delete-task');await waitFor(()=>!$('#task-dialog').hasAttribute('open'));
  assert.ok(!$('#task-list').textContent.includes('Tập trung'));
  click('[data-view=trash]');assert.match($('#task-list').textContent,/Tập trung/);click('#task-list [data-action=restore]');
  await waitFor(()=>!$('#task-list').textContent.includes('Tập trung'));click('[data-view=all]');assert.match($('#task-list').textContent,/Tập trung/);
  click('#search-trigger');$('#search-input').value='Đi dạo';$('#search-input').dispatchEvent(new window.Event('input',{bubbles:true}));
  assert.match($('#task-list').textContent,/Đi dạo/);assert.ok(!$('#task-list').textContent.includes('Tập trung'));click('#clear-search');
  click('#add-category');$('#category-form').elements.name.value='Sức khỏe';submit('#category-form');
  await waitFor(()=>!$('#category-dialog').hasAttribute('open'));assert.match($('#category-nav').textContent,/Sức khỏe/);
  click('#theme-button');assert.ok(window.document.body.classList.contains('dark'));assert.equal(window.localStorage.getItem('daymind-theme'),'dark');
  const store=await openStore(factory);const snapshot=await loadSnapshot(store);const reopened=new TaskRepository(new SQL.Database(snapshot.bytes));
  assert.equal(reopened.list().length,2);assert.equal(reopened.list().find(t=>t.title==='Đi dạo không có hạn').dueAt,null);
  assert.equal(reopened.list().find(t=>t.title==='Tập trung 25 phút').status,'TODO');assert.equal(reopened.categories().length,4);
  reopened.db.close();store.close();dom.window.close();
});
